<?php

trait getvar_trait {


	////////////////////////////////////////////////////////////////////////////
	// ARRAYACCESS - CHECK TO SEE IF $KEY EXISTS IN $_GET/$_POST
	////////////////////////////////////////////////////////////////////////////
	public function offsetExists($key) {
		return $this->_offsetExists($key);
	}




	////////////////////////////////////////////////////////////////////////////
	// ARRAYACCESS - GET THE $_GET/$_POST VALUE FOR THE GIVEN $KEY
	////////////////////////////////////////////////////////////////////////////
	public function offsetGet($key) {
		return $this->_offsetGet($key);
	}




	////////////////////////////////////////////////////////////////////////////
	// ARRAYACCESS - WE ARE A READ/DELETE ONLY INSTANCE, THROW EXCEPTION
	////////////////////////////////////////////////////////////////////////////
	public function offsetSet($key, $value) {
		$this->_offsetSet($key, $value);
	}




	////////////////////////////////////////////////////////////////////////////
	// ARRAYACCESS - REMOVE A $KEY FROM $_GET/$_POST
	////////////////////////////////////////////////////////////////////////////
	public function offsetUnset($key) {
		$this->_offsetUnset($key);
	}




	////////////////////////////////////////////////////////////////////////////
	// ITERATOR - GET THE CURRENT ITEM
	////////////////////////////////////////////////////////////////////////////
	public function current() {
		return current($_REQUEST);
	}




	////////////////////////////////////////////////////////////////////////////
	// ITERATOR - GET THE CURRENT KEY
	////////////////////////////////////////////////////////////////////////////
	public function key() {
		return key($_REQUEST);
	}




	////////////////////////////////////////////////////////////////////////////
	// ITERATOR - MOVE TO THE NEXT ITEM IN THE ARRAY
	////////////////////////////////////////////////////////////////////////////
	public function next() {
		next($_REQUEST);
	}




	////////////////////////////////////////////////////////////////////////////
	// ITERATOR - REWIND/RESET TO BEGINNING OF ARRAY
	////////////////////////////////////////////////////////////////////////////
	public function rewind() {
		reset($_REQUEST);
	}




	////////////////////////////////////////////////////////////////////////////
	// ITERATOR - IS THE CURRENT ARRAY ITEM A VALID ITEM
	////////////////////////////////////////////////////////////////////////////
	public function valid() {
		return current($_REQUEST) !== false;
	}

}
